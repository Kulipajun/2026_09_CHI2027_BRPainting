function initViewer() {
const paintings = window.paintings;

const paintingList = document.querySelector('#painting-list');
const frame = document.querySelector('#painting-frame');
const loading = document.querySelector('#loading');
const openPage = document.querySelector('#open-page');
const preferenceValue = document.querySelector('#preference-value');
const preferenceReason = document.querySelector('#preference-reason');
const feedbackValue = document.querySelector('#feedback-value');
const beforeCard = document.querySelector('#before-card');
const afterCard = document.querySelector('#after-card');
const beforeLabel = document.querySelector('#before-label');
const afterLabel = document.querySelector('#after-label');
const beforeComment = document.querySelector('#before-comment');
const afterComment = document.querySelector('#after-comment');
let selectedIndex = 0;
let condition = 'br';

paintings.forEach((painting, index) => {
  const button = document.createElement('button');
  button.className = index === 0 ? 'active' : '';
  button.title = `${painting.site} · ${painting.theme}`;
  button.innerHTML = `<strong>P${String(painting.participant).padStart(2, '0')}</strong><small>${painting.theme}</small>`;
  button.addEventListener('click', () => {
    selectedIndex = index;
    paintingList.querySelectorAll('button').forEach(item => item.classList.toggle('active', item === button));
    updateViewer();
  });
  paintingList.appendChild(button);
});

function currentPath() {
  const painting = paintings[selectedIndex];
  const conditionFolder = painting.folder === 'kashiwa1'
    ? (condition === 'br' ? 'BR' : 'NoneBR')
    : condition;
  return `${painting.folder}/${conditionFolder}/index.html`;
}

function updateViewer() {
  const painting = paintings[selectedIndex];
  const path = currentPath();
  loading.hidden = false;
  frame.src = path;
  openPage.href = path;
  preferenceValue.textContent = painting.preference;
  preferenceReason.textContent = painting.reason;
  feedbackValue.textContent = painting.feedback;
  beforeCard.dataset.condition = painting.firstCondition;
  afterCard.dataset.condition = painting.secondCondition;
  beforeLabel.textContent = `画前（${painting.firstCondition === 'br' ? 'BR' : 'Baseline'}条件）`;
  afterLabel.textContent = `画后（${painting.secondCondition === 'br' ? 'BR' : 'Baseline'}条件）`;
  beforeComment.textContent = painting.firstComment;
  afterComment.textContent = painting.secondComment;
  document.querySelectorAll('[data-condition]').forEach(item => item.classList.toggle('active', item.dataset.condition === condition));
}

document.querySelectorAll('[data-condition]').forEach(button => {
  button.addEventListener('click', () => {
    condition = button.dataset.condition;
    document.querySelectorAll('[data-condition]').forEach(item => item.classList.toggle('active', item.dataset.condition === condition));
    updateViewer();
  });
});

frame.addEventListener('load', () => { loading.hidden = true; });
updateViewer();
}

if (document.querySelector('#painting-list')) initViewer();
